import { app, BrowserWindow, Tray, Menu, Notification, ipcMain, nativeImage } from 'electron'
import path from 'path'
import fs from 'fs'
import Store from 'electron-store'

// 1. Setup Persistent Storage
const store = new Store({
  defaults: {
    dailyGoal: 2000,
    reminderMinutes: 45,
    todayIntake: 0,
    lastDate: new Date().toDateString()
  }
})

let mainWindow: BrowserWindow | null = null
let tray: Tray | null = null
let reminderTimer: NodeJS.Timeout | null = null

// Helper: Check if we need to reset daily counter
function checkDailyReset(): void {
  const today = new Date().toDateString()
  if (store.get('lastDate') !== today) {
    store.set('todayIntake', 0)
    store.set('lastDate', today)
  }
}

// ---------- Dynamic tray icons (0%..100% step 10) ----------
// Generated by `node scripts/generate-tray-icons.mjs` into resources/tray/.
function trayIconFor(pct: number): string {
  const level = Math.max(0, Math.min(100, Math.round(pct / 10) * 10))
  const file = `tray-${level}.png`
  const candidates = [
    // dev (electron-vite runs out/main -> ../../resources)
    path.join(__dirname, '../../resources/tray', file),
    // packaged (extraResources / resourcesPath)
    path.join(process.resourcesPath, 'tray', file),
    path.join(process.resourcesPath, 'app.asar.unpacked', 'resources', 'tray', file),
    // legacy fallback
    path.join(__dirname, '../../resources/icon.png')
  ]
  for (const c of candidates) {
    try {
      if (fs.existsSync(c)) return c
    } catch {
      /* ignore */
    }
  }
  return path.join(__dirname, '../../resources/icon.png')
}

function refreshTray(): void {
  if (!tray) return
  checkDailyReset()
  const intake = store.get('todayIntake') as number
  const goal = store.get('dailyGoal') as number
  const pct = goal > 0 ? (intake / goal) * 100 : 0
  const iconPath = trayIconFor(pct)
  try {
    const img = nativeImage.createFromPath(iconPath)
    // Keep tray icons crisp on HiDPI (our PNGs are 32px; template images look best on macOS)
    if (!img.isEmpty()) {
      if (process.platform === 'darwin') img.setTemplateImage(true)
      tray.setImage(img.resize({ width: 22, height: 22 }))
    } else {
      tray.setImage(iconPath)
    }
  } catch {
    try {
      tray.setImage(iconPath)
    } catch {
      /* keep old icon */
    }
  }
  tray.setToolTip(`H20Minder // ${intake}ml / ${goal}ml (${Math.floor(pct)}%)`)
}

function createWindow(): void {
  mainWindow = new BrowserWindow({
    width: 380,
    height: 560,
    resizable: false,
    frame: false, // Frameless for a modern widget look
    transparent: true, // Allows rounded corners/shadows + frosted glass
    show: false,
    webPreferences: {
      preload: path.join(__dirname, '../preload/index.js'),
      contextIsolation: true,
      nodeIntegration: false
    }
  })

  if (process.env.ELECTRON_RENDERER_URL) {
    mainWindow.loadURL(process.env.ELECTRON_RENDERER_URL)
  } else {
    mainWindow.loadFile(path.join(__dirname, '../renderer/index.html'))
  }

  mainWindow.once('ready-to-show', () => mainWindow?.show())
}

function createTray(): void {
  tray = new Tray(trayIconFor(0))

  const contextMenu = Menu.buildFromTemplate([
    { label: 'Show Widget', click: () => mainWindow?.show() },
    { type: 'separator' },
    { label: 'Quick Add 250ml', click: () => handleAddWater(250) },
    { label: 'Quick Add 500ml', click: () => handleAddWater(500) },
    { type: 'separator' },
    { label: 'Quit', click: () => app.quit() }
  ])

  tray.setToolTip('H20Minder')
  tray.setContextMenu(contextMenu)

  // Double click tray to show window
  tray.on('double-click', () => mainWindow?.show())

  refreshTray()
}

// ---------- Notification bridge services ----------
type NotifyService = 'none' | 'pushover' | 'telegram' | 'discord'

interface NotifyConfig {
  service: NotifyService
  pushover?: { token: string; userKey: string }
  telegram?: { botToken: string; chatId: string }
  discord?: { webhookUrl: string }
}

async function sendMobileNotification(cfg: NotifyConfig, title: string, body: string): Promise<void> {
  try {
    if (cfg.service === 'pushover' && cfg.pushover) {
      const url = 'https://api.pushover.net/1/messages.json'
      const params = new URLSearchParams({
        token: cfg.pushover.token,
        user: cfg.pushover.userKey,
        title,
        message: body,
      })
      await fetch(url, { method: 'POST', body: params })
    } else if (cfg.service === 'telegram' && cfg.telegram) {
      const url = `https://api.telegram.org/bot${cfg.telegram.botToken}/sendMessage`
      const params = new URLSearchParams({
        chat_id: cfg.telegram.chatId,
        text: `${title} — ${body}`,
        parse_mode: 'HTML',
      })
      await fetch(url, { method: 'POST', body: params })
    } else if (cfg.service === 'discord' && cfg.discord) {
      await fetch(cfg.discord.webhookUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ username: '💧 h2oMinder', content: `**${title}** — ${body}` }),
      })
    }
  } catch {
    /* notification bridge failed — the local notification already fired */
  }
}

// Load notification config from store
function getNotifyConfig(): NotifyConfig {
  const saved = store.get('notifyConfig')
  if (saved && typeof saved === 'object') {
    return saved as NotifyConfig
  }
  return { service: 'none' }
}

function startReminders(): void {
  if (reminderTimer) clearInterval(reminderTimer)

  const minutes = store.get('reminderMinutes') as number
  checkDailyReset()

  reminderTimer = setInterval(
    () => {
      checkDailyReset()
      const intake = store.get('todayIntake') as number
      const goal = store.get('dailyGoal') as number

      // Only remind if they haven't met their goal
      if (intake < goal) {
        const title = 'HYD_PROTOCOL // hydrate! 💧'
        const body = `You've had ${intake}ml. Goal is ${goal}ml. Drink a glass of water!`
        new Notification({
          title,
          body,
          silent: false
        }).show()

        // Also send to phone if configured
        sendMobileNotification(getNotifyConfig(), title, body)

        // Optional: Send event to UI if it's open
        mainWindow?.webContents.send('trigger-reminder')
      }
      refreshTray()
    },
    minutes * 60 * 1000
  )
}

// IPC Handlers (Connecting UI to Backend)
ipcMain.handle('get-today-intake', () => {
  checkDailyReset()
  return store.get('todayIntake')
})

ipcMain.handle('add-water', (_, amount: number) => {
  checkDailyReset()
  const current = store.get('todayIntake') as number
  const updated = Math.max(0, current + amount)
  store.set('todayIntake', updated)
  refreshTray()
  return updated
})

ipcMain.handle('get-settings', () => {
  return {
    dailyGoal: store.get('dailyGoal'),
    reminderMinutes: store.get('reminderMinutes')
  }
})

ipcMain.handle('save-settings', (_, settings) => {
  store.set('dailyGoal', settings.dailyGoal)
  store.set('reminderMinutes', settings.reminderMinutes)
  refreshTray()
  startReminders() // Restart timer with new settings
})

// --- Notification bridge settings ---
ipcMain.handle('get-notify-config', () => {
  const saved = store.get('notifyConfig')
  if (saved && typeof saved === 'object') {
    return saved as NotifyConfig
  }
  return { service: 'none' } as NotifyConfig
})

ipcMain.handle('save-notify-config', (_, cfg: NotifyConfig) => {
  store.set('notifyConfig', cfg)
  return { ok: true }
})

function handleAddWater(amount: number): void {
  checkDailyReset()
  const current = store.get('todayIntake') as number
  store.set('todayIntake', Math.max(0, current + amount))
  refreshTray()
  mainWindow?.webContents.send('data-updated') // Tell UI to refresh
}

app.whenReady().then(() => {
  createWindow()
  createTray()
  startReminders()
  // Midnight rollover check every minute
  setInterval(() => {
    const before = store.get('todayIntake') as number
    checkDailyReset()
    if ((store.get('todayIntake') as number) !== before) refreshTray()
  }, 60 * 1000)
})

app.on('window-all-closed', () => {
  // On macOS, keep app running in tray unless explicitly quit
  if (process.platform !== 'darwin') app.quit()
})
